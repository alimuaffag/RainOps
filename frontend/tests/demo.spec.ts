import { test, expect } from '@playwright/test'
test.skip(process.env.RAINOPS_DEMO_VERIFY !== '1', 'Requires an isolated demo database.')
test('demo gates API access and protects mutations with CSRF', async ({ page, request }) => {
  expect((await request.get('/health')).status()).toBe(200)
  expect((await request.get('/api/v1/incidents')).status()).toBe(401)
  await page.goto('/')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('اسم المستخدم').fill('reviewer')
  await page.getByLabel('كلمة المرور').fill('incorrect-password')
  await page.getByRole('button', { name: 'تسجيل الدخول', exact: true }).click()
  await expect(page).toHaveURL(/error/)
  await page.getByLabel('اسم المستخدم').fill('reviewer')
  await page.getByLabel('كلمة المرور').fill(process.env.DEMO_PASSWORD!)
  await page.getByRole('button', { name: 'تسجيل الدخول', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'ملخص البلاغات' })).toBeVisible()
  expect((await page.request.post('/api/v1/incidents', { data: {} })).status()).toBe(403)
  const session = (await page.context().cookies()).find((cookie) => cookie.name === 'JSESSIONID')
  expect(session?.httpOnly).toBe(true)
  expect(session?.sameSite).toBe('Lax')
})
test('reviewer creates, updates and resolves an incident in the deployed frontend', async ({
  page,
}) => {
  await page.goto('/login')
  await page.getByLabel('اسم المستخدم').fill('reviewer')
  await page.getByLabel('كلمة المرور').fill(process.env.DEMO_PASSWORD!)
  await page.getByRole('button', { name: 'تسجيل الدخول', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'ملخص البلاغات' })).toBeVisible()
  const summary = await (await page.request.get('/api/v1/dashboard/summary')).json()
  expect(summary.total).toBeGreaterThanOrEqual(6)
  await page.goto('/incidents/new')
  await page.getByLabel('عنوان البلاغ').fill('اختبار النشر')
  await page.getByLabel('وصف البلاغ').fill('بلاغ اختبار مستقل')
  await page.getByLabel('الحي', { exact: false }).fill('حي الاختبار')
  await page.getByLabel('وصف الموقع').fill('موقع افتراضي')
  await page.getByRole('button', { name: 'إنشاء البلاغ', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'اختبار النشر', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'تعديل التفاصيل' }).click()
  await page.getByLabel('الأولوية', { exact: false }).selectOption('HIGH')
  await page.getByRole('button', { name: 'حفظ التعديلات' }).click()
  await page.getByRole('button', { name: 'بدء المعالجة' }).click()
  await page.getByRole('button', { name: 'تأكيد حل البلاغ' }).click()
  await expect(page.getByText('تاريخ الحل', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.timeline li')).toHaveCount(3)
  await page.goto('/logout')
  await page.getByRole('button', { name: 'تسجيل الخروج', exact: false }).click()
  expect((await page.request.get('/api/v1/incidents')).status()).toBe(401)
})
